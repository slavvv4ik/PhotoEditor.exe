# -*- coding: utf-8 -*-
"""Обработка ЭИ, частотно-селективная фильтрация:
Гауссов низкочастотный срез в частотной области (2Д БПФ) подавляет
пространственные масштабы мельче зерна текстуры, крупный объект
и его контуры сохраняются; далее — растяжение до 0…255."""

import os
import sys

import numpy as np
from PIL import Image

for _поток in (sys.stdout, sys.stderr):
    try:
        _поток.reconfigure(encoding="utf-8")
    except Exception:
        pass

# ============================ НАСТРОЙКИ ============================
# ВСЕ параметры, влияющие на выходное изображение, — только в этом блоке.
БАЗОВАЯ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_домик.png"                       # входное изображение (ввод ТОЛЬКО здесь)
ОБРАБОТАННОЕ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_ЧФ.png"     # выходное изображение
СИГМА = 2.0    # ширина среза, пкс; > 0, практика 1…10 (между зерном и объектом)
# ==================================================================


def загрузить_полутоновое(путь):
    """Полутоновый массив float64 (H, W) со значениями яркости 0…255."""
    with Image.open(путь) as исходное:
        return np.asarray(исходное.convert("L"), dtype=np.float64)


def обработать(массив):
    """Гауссов низкочастотный срез: H(ρ) = exp(−2·(π·σ·ρ)²), ρ — цикл/пиксель."""
    высота, ширина = массив.shape
    спектр = np.fft.fftshift(np.fft.fft2(массив))
    u = np.arange(ширина) - ширина // 2
    v = np.arange(высота) - высота // 2
    U, V = np.meshgrid(u, v)
    ро = np.sqrt((U / ширина) ** 2 + (V / высота) ** 2)           # цикл/пиксель
    характеристика = np.exp(-2.0 * (np.pi * СИГМА * ро) ** 2)
    результат = np.fft.ifft2(np.fft.ifftshift(спектр * характеристика)).real
    # растяжение до диапазона яркости полутонового формата 0…255
    мин, макс = float(результат.min()), float(результат.max())
    return (результат - мин) / (макс - мин + 1e-12) * 255.0


def main():
    if not os.path.isfile(БАЗОВАЯ):
        print(f"ОШИБКА: файл изображения не найден: {БАЗОВАЯ}")
        sys.exit(1)
    исходное = загрузить_полутоновое(БАЗОВАЯ)
    обработанное = обработать(исходное)
    Image.fromarray(np.round(np.clip(обработанное, 0, 255)).astype(np.uint8)).save(ОБРАБОТАННОЕ)
    print(f"обработанное изображение сохранено: {ОБРАБОТАННОЕ}")


if __name__ == "__main__":
    main()