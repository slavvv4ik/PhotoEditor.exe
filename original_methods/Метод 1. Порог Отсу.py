"""Обработка ЭИ, подавление фона порогом Отсу («контраст»):
медианный фильтр → порог Отсу → мягкое подавление фона (ниже порога — 0,
выше — растяжение до 0…255) → медианный фильтр"""

import os
import sys

import numpy as np
from PIL import Image, ImageFilter

for _поток in (sys.stdout, sys.stderr):
    try:
        _поток.reconfigure(encoding="utf-8")
    except Exception:
        pass

# ============================ НАСТРОЙКИ ============================
# ВСЕ параметры, влияющие на выходное изображение, — только в этом блоке.
БАЗОВАЯ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_дача.png"                       # входное изображение (ввод ТОЛЬКО здесь)
ОБРАБОТАННОЕ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_порог_Отсу.png"     # выходное изображение
ОКНО_СГЛАЖИВАНИЯ = 5     # окно первого медианного фильтра; нечётное ≥ 3, практика 3…51
ОКНО_УБОРКИ = 3          # окно финального медианного фильтра; нечётное ≥ 3, практика 3…21
ПЕРЦЕНТИЛЬ_ВЕРХА = 99.5  # перцентиль верхней границы растяжения; 0…100, практика 95…99.9
# ==================================================================


def загрузить_полутоновое(путь):
    """Полутоновый массив float64 (H, W) со значениями яркости 0…255."""
    with Image.open(путь) as исходное:
        return np.asarray(исходное.convert("L"), dtype=np.float64)


def порог_Отсу(изображение):
    """Классический порог Отсу по гистограмме яркости.
    256 уровней и диапазон 0…255 — сетка яркости полутонового формата."""
    гистограмма, _ = np.histogram(изображение.ravel(), bins=256, range=(0, 256))
    вероятность = гистограмма.astype(np.float64)
    вероятность /= вероятность.sum()
    уровни = np.arange(256)
    омега = np.cumsum(вероятность)
    мю = np.cumsum(вероятность * уровни)
    мю_полный = мю[-1]
    дисперсия_межклассовая = (мю_полный * омега - мю) ** 2 / (омега * (1 - омега) + 1e-12)
    return float(np.argmax(дисперсия_межклассовая))


def обработать(массив):
    """Подавление фона и растяжение контраста объекта."""
    исходное = Image.fromarray(np.round(np.clip(массив, 0, 255)).astype(np.uint8))
    сглаженное = np.asarray(исходное.filter(ImageFilter.MedianFilter(ОКНО_СГЛАЖИВАНИЯ)),
                           dtype=np.float64)
    порог = порог_Отсу(сглаженное)
    верх = float(np.percentile(сглаженное, ПЕРЦЕНТИЛЬ_ВЕРХА))  # яркость «светлого» объекта
    усиление = 255.0 / max(верх - порог, 1.0)     # 255 — верх диапазона формата
    результат = np.clip((сглаженное - порог) * усиление, 0.0, 255.0)
    результат = np.asarray(
        Image.fromarray(результат.astype(np.uint8)).filter(ImageFilter.MedianFilter(ОКНО_УБОРКИ)),
        dtype=np.float64)
    return результат


def main():
    if not os.path.isfile(БАЗОВАЯ):
        print(f"ОШИБКА: файл изображения не найден: {БАЗОВАЯ}")
        sys.exit(1)
    исходное = загрузить_полутоновое(БАЗОВАЯ)
    обработанное = обработать(исходное)
    Image.fromarray(np.round(np.clip(обработанное, 0, 255)).astype(np.uint8)).save(ОБРАБОТАННОЕ)
    print(f"обработанное изображение сохранено: {ОБРАБОТАННОЕ}")


if __name__ == "__main__":
    main()