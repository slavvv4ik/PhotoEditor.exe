# -*- coding: utf-8 -*-
"""Обработка ЭИ, математическая морфология:
морфологическое открытие (эрозия + дилатация) с окном R×R удаляет яркие
включения мельче R (зёрна текстуры), объект много крупнее R сохраняется;
далее — растяжение до 0…255."""

import os
import sys

import numpy as np
from PIL import Image, ImageFilter

for _поток in (sys.stdout, sys.stderr):
    try:
        _поток.reconfigure(encoding="utf-8")
    except Exception:
        pass

# ============================ НАСТРОЙКИ ============================
# ВСЕ параметры, влияющие на выходное изображение, — только в этом блоке.
БАЗОВАЯ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_школа.png"                       # входное изображение (ввод ТОЛЬКО здесь)
ОБРАБОТАННОЕ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_ММ.png"     # выходное изображение
РАЗМЕР = 7    # окно открытия R×R; нечётное ≥ 3, практика 3…31 (больше зерна, меньше объекта)
# ==================================================================


def загрузить_полутоновое(путь):
    """Полутоновый массив float64 (H, W) со значениями яркости 0…255."""
    with Image.open(путь) as исходное:
        return np.asarray(исходное.convert("L"), dtype=np.float64)


def обработать(массив):
    """Морфологическое открытие: эрозия (MinFilter) + дилатация (MaxFilter)."""
    исходное = Image.fromarray(np.round(np.clip(массив, 0, 255)).astype(np.uint8))
    эрозия = исходное.filter(ImageFilter.MinFilter(РАЗМЕР))
    открытие = эрозия.filter(ImageFilter.MaxFilter(РАЗМЕР))
    результат = np.asarray(открытие, dtype=np.float64)
    # растяжение до диапазона яркости полутонового формата 0…255
    мин, макс = float(результат.min()), float(результат.max())
    return (результат - мин) / (макс - мин + 1e-12) * 255.0


def main():
    if not os.path.isfile(БАЗОВАЯ):
        print(f"ОШИБКА: файл изображения не найден: {БАЗОВАЯ}")
        sys.exit(1)
    исходное = загрузить_полутоновое(БАЗОВАЯ)
    обработанное = обработать(исходное)
    Image.fromarray(np.round(np.clip(обработанное, 0, 255)).astype(np.uint8)).save(ОБРАБОТАННОЕ)
    print(f"обработанное изображение сохранено: {ОБРАБОТАННОЕ}")


if __name__ == "__main__":
    main()