"""Обработка ЭИ, согласованный фильтр «квадрат габарита объекта
минус кольцо»: отклик фильтра (оптимальный линейный детектор известного
сигнала в помехе с неизвестным фоном) используется как мягкая маска [0; 1]
исходного изображения — фон подавляется, детали объекта сохраняются.
Габарит объекта L оценивается по площади сегмента порогом Отсу."""

import os
import sys

import numpy as np
from PIL import Image, ImageFilter

for _поток in (sys.stdout, sys.stderr):
    try:
        _поток.reconfigure(encoding="utf-8")
    except Exception:
        pass

# ============================ НАСТРОЙКИ ============================
# ВСЕ параметры, влияющие на выходное изображение, — только в этом блоке.
БАЗОВАЯ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_домик.png"                       # входное изображение (ввод ТОЛЬКО здесь)
ОБРАБОТАННОЕ = "D:/ЭКСПЕРИМЕНТЫ/input_images/ЭИ_СФ.png"     # выходное изображение
ОКНО_СГЛАЖИВАНИЯ = 5      # медианный фильтр перед оценкой габарита; нечётное ≥ 3, практика 3…21
СТЕПЕНЬ_ЗАТВОРА = 2.0     # жёсткость маски; ≥ 0, практика 1…5 (0 — маска отключена)
ПЕРЦЕНТИЛЬ_МАСКИ = 99.5   # перцентиль нормировки маски; 0…100, практика 90…99.9
МНОЖИТЕЛЬ_КОЛЬЦА = 2      # наружное кольцо = МНОЖИТЕЛЬ × габарит; целое ≥ 2, практика 2…4
# ==================================================================


def загрузить_полутоновое(путь):
    """Полутоновый массив float64 (H, W) со значениями яркости 0…255."""
    with Image.open(путь) as исходное:
        return np.asarray(исходное.convert("L"), dtype=np.float64)


def порог_Отсу(изображение):
    """Классический порог Отсу по гистограмме яркости.
    256 уровней и диапазон 0…255 — сетка яркости полутонового формата."""
    гистограмма, _ = np.histogram(изображение.ravel(), bins=256, range=(0, 256))
    вероятность = гистограмма.astype(np.float64)
    вероятность /= вероятность.sum()
    уровни = np.arange(256)
    омега = np.cumsum(вероятность)
    мю = np.cumsum(вероятность * уровни)
    мю_полный = мю[-1]
    дисперсия_межклассовая = (мю_полный * омега - мю) ** 2 / (омега * (1 - омега) + 1e-12)
    return float(np.argmax(дисперсия_межклассовая))


def локальное_среднее(f, k):
    """Среднее в квадратном окне k×k (через БПФ), нормированное по
    перекрытию окна с изображением (без граничных артефактов)."""
    высота, ширина = f.shape
    ядро = np.ones((k, k), dtype=np.float64) / (k * k)
    размер = (высота + k - 1, ширина + k - 1)
    K = np.fft.fft2(ядро, s=размер)
    числитель = np.fft.ifft2(np.fft.fft2(f, s=размер) * K).real
    знаменатель = np.fft.ifft2(np.fft.fft2(np.ones_like(f), s=размер) * K).real
    среднее = числитель / np.maximum(знаменатель, 1e-9)
    return среднее[k // 2:k // 2 + высота, k // 2:k // 2 + ширина]


def обработать(массив):
    """Отклик «квадрат L×L минус кольцо» → маска в степени затвора → f·маска."""
    исходное = Image.fromarray(np.round(np.clip(массив, 0, 255)).astype(np.uint8))
    сглаженное = np.asarray(исходное.filter(ImageFilter.MedianFilter(ОКНО_СГЛАЖИВАНИЯ)),
                           dtype=np.float64)
    порог = порог_Отсу(сглаженное)
    площадь = int((сглаженное > порог).sum())                 # площадь объекта
    высота, ширина = массив.shape
    сторона = max(3, int(round(np.sqrt(площадь))) | 1)        # габарит L (нечётный)
    окрестность = min(МНОЖИТЕЛЬ_КОЛЬЦА * сторона + 1, min(высота, ширина))
    if окрестность <= сторона:                                # защита от вырождения кольца
        окрестность = сторона + 2
    внутр = локальное_среднее(массив, сторона)
    внеш = локальное_среднее(массив, окрестность)
    s_in, s_out = float(сторона ** 2), float(окрестность ** 2)
    отклик = внутр - (внеш * s_out - внутр * s_in) / (s_out - s_in)
    вес = np.clip(отклик / (np.percentile(отклик, ПЕРЦЕНТИЛЬ_МАСКИ) + 1e-12), 0.0, 1.0)
    вес = вес ** СТЕПЕНЬ_ЗАТВОРА
    результат = массив * вес
    # растяжение до диапазона яркости полутонового формата 0…255
    мин, макс = float(результат.min()), float(результат.max())
    return (результат - мин) / (макс - мин + 1e-12) * 255.0


def main():
    if not os.path.isfile(БАЗОВАЯ):
        print(f"ОШИБКА: файл изображения не найден: {БАЗОВАЯ}")
        sys.exit(1)
    исходное = загрузить_полутоновое(БАЗОВАЯ)
    обработанное = обработать(исходное)
    Image.fromarray(np.round(np.clip(обработанное, 0, 255)).astype(np.uint8)).save(ОБРАБОТАННОЕ)
    print(f"обработанное изображение сохранено: {ОБРАБОТАННОЕ}")


if __name__ == "__main__":
    main()